create extension if not exists "pgcrypto";

-- ------------------------------------------------------------
-- 1) profiles: auth.users 1:1 프로필 (roster 대체)
-- ------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  nickname text not null default '',
  role text not null default '' check (role in ('', 'professor', 'student', 'practitioner')),
  affiliation text not null default '',       -- 소속 (학교/기관/회사)
  job_title text not null default '',         -- 실무자용 직무
  interests text[] not null default '{}',     -- 관심 MICE 분야 (Meeting/Incentive/Convention/Exhibition)
  avatar_color text not null default '#3b7eff',
  onboarded boolean not null default false,
  created_at timestamptz not null default now()
);

-- 가입(이메일 인증 완료 후 첫 세션 생성) 시 최소 프로필 자동 생성
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- ------------------------------------------------------------
-- 2) classrooms: 교수자가 생성, 학생/실무자는 랜덤 코드로 등록
-- ------------------------------------------------------------
create table if not exists public.classrooms (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  code text not null unique check (code ~ '^[A-Z0-9]{6}$'),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  owner_name text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.classroom_members (
  id bigint generated by default as identity primary key,
  classroom_id uuid not null references public.classrooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  user_name text not null default '',
  member_role text not null default 'student',
  created_at timestamptz not null default now(),
  unique(classroom_id, user_id)
);

create index if not exists classroom_members_user_idx on public.classroom_members(user_id);
create index if not exists classroom_members_classroom_idx on public.classroom_members(classroom_id);

-- 코드로 교실 가입 (코드 노출 없이 조회+가입을 한 번에)
create or replace function public.join_classroom_by_code(p_code text, p_user_name text)
returns table (classroom_id uuid, classroom_name text)
language plpgsql
security definer set search_path = public
as $$
declare
  v_room public.classrooms%rowtype;
begin
  select * into v_room from public.classrooms c where c.code = upper(trim(p_code));
  if not found then
    raise exception 'CLASSROOM_CODE_INVALID';
  end if;
  insert into public.classroom_members (classroom_id, user_id, user_name)
  values (v_room.id, auth.uid(), coalesce(p_user_name, ''))
  on conflict (classroom_id, user_id) do nothing;
  return query select v_room.id, v_room.name;
end;
$$;

-- ------------------------------------------------------------
-- 3) 기존 테이블 확장: 교실 스코프 + 숨기기
--    (teams.name PK는 유지 → 팀 이름은 전역 유일. 교실 간 동일 팀명은 불가)
-- ------------------------------------------------------------
alter table public.teams add column if not exists classroom_id uuid references public.classrooms(id) on delete cascade;
alter table public.events add column if not exists classroom_id uuid references public.classrooms(id) on delete cascade;
alter table public.events add column if not exists hidden boolean not null default false;

create index if not exists teams_classroom_idx on public.teams(classroom_id);
create index if not exists events_classroom_idx on public.events(classroom_id);

-- uid 컬럼(text)은 그대로 두고 auth.uid()::text 를 저장합니다 (마이그레이션 최소화).

-- ------------------------------------------------------------
-- 4) 팀 이름 변경 RPC (팀장 전용, FK on update cascade로 events/memberships 자동 반영)
-- ------------------------------------------------------------
create or replace function public.rename_team(p_old_name text, p_new_name text)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  v_team public.teams%rowtype;
begin
  select * into v_team from public.teams t where t.name = trim(p_old_name);
  if not found then
    raise exception 'TEAM_NOT_FOUND';
  end if;
  if v_team.leader_uid is distinct from auth.uid()::text then
    raise exception 'NOT_TEAM_LEADER';
  end if;
  if exists (select 1 from public.teams t where t.name = trim(p_new_name)) then
    raise exception 'TEAM_NAME_TAKEN';
  end if;
  update public.teams set name = trim(p_new_name) where name = v_team.name;
end;
$$;

-- ------------------------------------------------------------
-- 5) 팀원 내보내기 RPC (팀장 전용)
-- ------------------------------------------------------------
create or replace function public.kick_team_member(p_team_name text, p_member_uid text)
returns void
language plpgsql
security definer set search_path = public
as $$
declare
  v_team public.teams%rowtype;
begin
  select * into v_team from public.teams t where t.name = trim(p_team_name);
  if not found then
    raise exception 'TEAM_NOT_FOUND';
  end if;
  if v_team.leader_uid is distinct from auth.uid()::text then
    raise exception 'NOT_TEAM_LEADER';
  end if;
  if p_member_uid = auth.uid()::text then
    raise exception 'CANNOT_KICK_SELF';
  end if;
  delete from public.team_memberships
  where team_name = v_team.name and uid = p_member_uid;
end;
$$;

-- ------------------------------------------------------------
-- 6) RLS
-- ------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.classrooms enable row level security;
alter table public.classroom_members enable row level security;

drop policy if exists "profiles_read_all" on public.profiles;
create policy "profiles_read_all" on public.profiles for select using (true);
drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles for update
  using (auth.uid() = id) with check (auth.uid() = id);
drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles for insert
  with check (auth.uid() = id);

drop policy if exists "classrooms_read_all" on public.classrooms;
create policy "classrooms_read_all" on public.classrooms for select using (true);
drop policy if exists "classrooms_insert_professor" on public.classrooms;
create policy "classrooms_insert_professor" on public.classrooms for insert
  with check (
    auth.uid() = owner_id
    and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'professor')
  );
drop policy if exists "classrooms_update_owner" on public.classrooms;
create policy "classrooms_update_owner" on public.classrooms for update
  using (auth.uid() = owner_id) with check (auth.uid() = owner_id);
drop policy if exists "classrooms_delete_owner" on public.classrooms;
create policy "classrooms_delete_owner" on public.classrooms for delete
  using (auth.uid() = owner_id);

drop policy if exists "classroom_members_read_all" on public.classroom_members;
create policy "classroom_members_read_all" on public.classroom_members for select using (true);
drop policy if exists "classroom_members_insert_self" on public.classroom_members;
create policy "classroom_members_insert_self" on public.classroom_members for insert
  with check (auth.uid() = user_id);
drop policy if exists "classroom_members_delete_self_or_owner" on public.classroom_members;
create policy "classroom_members_delete_self_or_owner" on public.classroom_members for delete
  using (
    auth.uid() = user_id
    or exists (select 1 from public.classrooms c where c.id = classroom_id and c.owner_id = auth.uid())
  );

-- 기존 permissive 정책은 anon 기준이었으므로, 최소한 쓰기는 로그인 사용자로 제한
drop policy if exists "teams_write_all" on public.teams;
create policy "teams_write_all" on public.teams for insert to authenticated with check (true);
drop policy if exists "teams_update_all" on public.teams;
create policy "teams_update_all" on public.teams for update to authenticated using (true) with check (true);

drop policy if exists "team_memberships_write_all" on public.team_memberships;
create policy "team_memberships_write_all" on public.team_memberships for insert to authenticated with check (true);
drop policy if exists "team_memberships_update_all" on public.team_memberships;
create policy "team_memberships_update_all" on public.team_memberships for update to authenticated using (true) with check (true);

drop policy if exists "events_write_all" on public.events;
create policy "events_write_all" on public.events for insert to authenticated with check (true);
drop policy if exists "events_update_all" on public.events;
create policy "events_update_all" on public.events for update to authenticated using (true) with check (true);
drop policy if exists "events_delete_all" on public.events;
create policy "events_delete_all" on public.events for delete to authenticated using (true);

drop policy if exists "messages_write_all" on public.messages;
create policy "messages_write_all" on public.messages for insert to authenticated with check (true);

-- Storage: 업로드도 로그인 사용자만
drop policy if exists "event_files_insert" on storage.objects;
create policy "event_files_insert" on storage.objects for insert to authenticated
  with check (bucket_id = 'event-files');

