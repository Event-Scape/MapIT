-- ============================================================
-- MapIT schema v6: 좋아요/피드백 전용 테이블 신설 (PR A)
-- Supabase SQL Editor에서 이 파일을 실행하세요.
-- 범위: 테이블 생성 + RLS만 다룹니다. 아직 아무 코드도 이 테이블을
-- 참조하지 않으므로, 이 파일을 실행해도 기존 동작(events.liked_by/
-- events.feedbacks 기반 좋아요·피드백)은 전혀 바뀌지 않습니다.
-- events 테이블 자체(컬럼, RLS)는 이 파일에서 건드리지 않습니다.
--
-- 백필(PR B) 관련 결정 사항은 이 파일에 컬럼으로 반영하지 않습니다.
-- author_uid를 nullable로 둔 이유는 기존 데이터의 백필을 허용하기
-- 위해서입니다. 신규 피드백은 INSERT RLS(event_feedbacks_insert,
-- with check author_uid = auth.uid()::text)에 의해 항상 author_uid가
-- 채워진 상태로만 생성되므로, NULL은 백필된 과거 데이터만 가질 수
-- 있는 예외 상태입니다. 순서 보존용 컬럼(legacy_order 등)처럼
-- 백필 전략에만 필요한 결정은 PR B에서 별도 ALTER TABLE로 추가합니다.
-- ============================================================

-- ------------------------------------------------------------
-- 1) event_likes: 이벤트별 좋아요 (사용자 1명당 이벤트 1개에 최대 1행)
-- ------------------------------------------------------------
create table if not exists public.event_likes (
  event_id uuid not null references public.events(id) on delete cascade,
  uid text not null,
  created_at timestamptz not null default now(),
  primary key (event_id, uid)
);

alter table public.event_likes enable row level security;

create policy event_likes_read on public.event_likes
  for select to authenticated using (true);

create policy event_likes_insert on public.event_likes
  for insert to authenticated with check (uid = auth.uid()::text);

create policy event_likes_delete on public.event_likes
  for delete to authenticated using (uid = auth.uid()::text);

-- ------------------------------------------------------------
-- 2) event_feedbacks: 이벤트별 피드백 (한 사용자가 여러 개 남길 수 있음)
-- ------------------------------------------------------------
create table if not exists public.event_feedbacks (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.events(id) on delete cascade,
  -- author_uid는 NOT NULL이 아닙니다. events.feedbacks(jsonb)의 과거 데이터에는
  -- user_name만 있고 uid가 없어 백필 시 author_uid를 복원할 수 없는 행이
  -- 있을 수 있습니다(사용자 이름 변경/탈퇴/이전 프로필 등). NOT NULL로 두면
  -- 그런 행의 백필 INSERT 자체가 실패합니다. 신규 피드백은 아래 INSERT
  -- 정책(with check author_uid = auth.uid()::text)에 의해 항상 author_uid가
  -- 채워진 채로만 생성되므로, NULL은 백필된 과거 데이터만 가질 수 있는
  -- 예외 상태입니다. author_uid가 NULL인 행은 event_feedbacks_delete
  -- 정책(author_uid = auth.uid()::text)이 NULL과 어떤 값도 같다고
  -- 판단하지 않으므로 자동으로 "삭제 불가"로 처리되어 별도 조건 없이
  -- 안전합니다.
  author_uid text,
  author_name text not null,
  author_role text not null,
  content text not null,
  created_at timestamptz not null default now()
);

-- event_id로 필터링 + created_at 정렬이 함께 일어나는 조회 패턴
-- (messages_room_created_at_idx와 동일한 목적의 복합 인덱스)
create index if not exists event_feedbacks_event_id_created_at_idx
  on public.event_feedbacks(event_id, created_at);

alter table public.event_feedbacks enable row level security;

create policy event_feedbacks_read on public.event_feedbacks
  for select to authenticated using (true);

create policy event_feedbacks_insert on public.event_feedbacks
  for insert to authenticated with check (author_uid = auth.uid()::text);

create policy event_feedbacks_delete on public.event_feedbacks
  for delete to authenticated using (author_uid = auth.uid()::text);
